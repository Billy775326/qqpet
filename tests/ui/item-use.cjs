const {app,BrowserWindow,ipcMain}=require('electron')
const {readFileSync,writeFileSync,mkdtempSync,renameSync}=require('node:fs')
const {resolve,join}=require('node:path')
const {pathToFileURL}=require('node:url')
const assert=require('node:assert/strict')
const {resizeViewport}=require('./viewport.cjs')
const {startSave,applyPatch}=require(resolve('dist/ui-inventory-save.cjs'))
const profile=mkdtempSync(resolve('dist/item-use-profile-'))
app.setPath('userData',profile);app.setPath('sessionData',profile);app.setAppLogsPath(join(profile,'logs'))
const file=join(profile,'save.json')
let disk=startSave(null),fail=false
disk.havePet=true;disk.settings.quiet=true
disk.selfGoodDatas.nums=['_growth*5']
writeFileSync(file,JSON.stringify(disk))
ipcMain.handle('fixture:load',()=>JSON.parse(readFileSync(file,'utf8')))
ipcMain.on('fixture:save',(event,patch)=>{
  try{
    const next=structuredClone(disk);applyPatch(next,patch)
    if(fail)throw Error('Simulated disk failure')
    writeFileSync(file+'.tmp',JSON.stringify(next));renameSync(file+'.tmp',file);disk=next;event.returnValue=null
  }catch(error){event.returnValue=String(error)}
})
app.whenReady().then(async()=>{
  const prepared=JSON.parse(readFileSync('dist/ui-item-use-prepared.json','utf8'))
  const assetRoot=pathToFileURL(resolve(process.env.QQPET_TEST_RESOURCES||'resources')+'/').href
  const html=resolve('dist/item-use-test.html')
  writeFileSync(html,'<!doctype html><meta charset="UTF-8"><base href="'+assetRoot+'"><style>'+prepared.css.replaceAll('url(/pet/','url('+assetRoot+'pet/')+'</style><body>')
  const win=new BrowserWindow({width:800,height:600,useContentSize:true,show:false,webPreferences:{preload:join(__dirname,'shop-preload.cjs'),sandbox:true,contextIsolation:true,offscreen:true,backgroundThrottling:false}})
  win.webContents.setAudioMuted(true)
  const evaluate=code=>win.webContents.executeJavaScript(code)
  const click=selector=>evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing '+${JSON.stringify(selector)});e.click();return true})()`)
  await win.loadFile(html);await resizeViewport(win,800,600);await evaluate('(async()=>{'+prepared.code+';return true})()')
  // Synthetic normal sources only, never a change to the real item catalogue.
  await evaluate("testProtection['t0002']='rare';testProtection.growth='discontinued';testProtection['60001']='rare';true")
  const before=JSON.stringify(disk)
  await evaluate("fixture.use('toy','t0002');true")
  assert.equal(await evaluate("document.querySelectorAll('.ui-window').length"),1)
  assert.match(await evaluate("document.querySelector('.msg').textContent"),/稀有/)
  assert.equal(JSON.stringify(disk),before)
  await evaluate("window.cancelled=document.querySelector('.windowViewButSubmit');true")
  await click('.windowViewBut');await evaluate('cancelled.click();fixture.run();true')
  assert.equal(JSON.stringify(disk),before,'cancel and stale submit leave the fixture save untouched')
  await evaluate("fixture.use('toy','t0002');true")
  await click('.windowViewButSubmit')
  assert.equal(await evaluate("fixture.quantityOf('toy','t0002')"),1,'confirmation still respects animation timing')
  await evaluate('fixture.run();fixture.run();true')
  assert.equal(await evaluate("fixture.quantityOf('toy','t0002')"),0)
  assert.equal(await evaluate('itemUseCounts'),1)
  await evaluate("fixture.use('nums','growth');true")
  assert.match(await evaluate("document.querySelector('.msg').textContent"),/绝版/)
  assert.equal(await evaluate("document.querySelector('.chooseNum .content').textContent"),'1')
  await click('.quantityButton.add')
  assert.match(await evaluate("document.querySelector('.msg').textContent"),/消耗 2 份 \/ 背包 5 份/)
  const cases=[]
  for(const [w,h,dpr]of [[800,600,1],[640,480,1.5],[360,640,2],[320,240,2]]){
    await resizeViewport(win,w,h,dpr)
    const check=await evaluate(`(()=>{const v=document.querySelector('.ui-window'),m=v.querySelector('.msg'),s=v.querySelector('.windowViewButSubmit'),q=v.querySelector('.chooseNum');const r=v.getBoundingClientRect(),mr=m.getBoundingClientRect(),qr=q.getBoundingClientRect(),sr=s.getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,clipped:m.scrollHeight>m.clientHeight+1,overlap:mr.bottom>qr.top+1||qr.bottom>sr.top+1}})()`)
    assert.ok(check.left>=-1&&check.right<=w+1&&check.top>=-1&&check.bottom<=h+1,JSON.stringify({w,h,check}))
    assert.equal(check.clipped,false,'all warning text must fit')
    assert.equal(check.overlap,false,'text, quantity and confirmation must not overlap')
    cases.push({w,h,dpr})
  }
  await resizeViewport(win,800,600,1)
  await evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))).then(()=>true)')
  writeFileSync('dist/item-use-discontinued.png',(await win.webContents.capturePage()).toPNG())
  await evaluate("window.accepted=document.querySelector('.windowViewButSubmit');true")
  await click('.windowViewButSubmit');await evaluate('accepted.click();true')
  assert.equal(await evaluate("fixture.quantityOf('nums','growth')"),3)
  await evaluate("fixture.info.health=3;fixture.use('medicine','60001');true")
  assert.match(await evaluate("document.querySelector('.msg').textContent"),/尚未死亡/)
  await evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))).then(()=>true)')
  writeFileSync('dist/item-use-rare.png',(await win.webContents.capturePage()).toPNG())
  await click('.windowViewButSubmit')
  assert.equal(await evaluate('fixture.info.health'),5)
  assert.equal(await evaluate("document.querySelectorAll('.ui-window').length"),0,'protected revival never creates a second confirmation')
  await evaluate("fixture.addGood('toy','t0002',1);fixture.info.mood=1;fixture.info.hunger=fixture.save.petComputedlInfo.hungerMax;fixture.info.clean=fixture.save.petComputedlInfo.cleanMax;fixture.info.sweetHeart=true;fixture.info.sweetHeartOverTime=Date.now()/1000+10000;fixture.save.settings.careToyId='t0002';fixture.save.settings.careAutoBuy=true;true")
  const careBefore=readFileSync(file,'utf8')
  for(let i=0;i<3;i++)assert.equal(await evaluate('fixture.selfCare()'),false)
  assert.equal(readFileSync(file,'utf8'),careBefore)
  assert.equal(await evaluate("document.querySelectorAll('.ui-window').length"),0)
  await evaluate('new Promise(r=>requestAnimationFrame(()=>requestAnimationFrame(r))).then(()=>true)')
  writeFileSync('dist/item-use-results.json',JSON.stringify({syntheticSourceFixtures:true,originalSkin:true,cancel:true,staleClicks:true,quantity:true,revival:true,careSkipped:true,cases},null,2))
  console.log('Item use UI verified: original skin, rare/discontinued synthetic sources, cancel, stale submit, quantity, revival, automatic-care protection and four viewports')
  win.destroy();app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
