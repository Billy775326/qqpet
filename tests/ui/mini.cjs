const {app,BrowserWindow}=require('electron')
const {readFileSync,writeFileSync,mkdtempSync}=require('node:fs')
const {resolve,join}=require('node:path')
const {pathToFileURL}=require('node:url')
const assert=require('node:assert/strict')
const profile=mkdtempSync(resolve('dist/source-mini-profile-'))
app.setPath('userData',profile);app.setPath('sessionData',profile);app.setAppLogsPath(join(profile,'logs'))
app.whenReady().then(async()=>{
  const prepared=JSON.parse(readFileSync('dist/ui-mini-prepared.json','utf8'))
  const boot=prepared.setup+'\n'+prepared.code+';true'
  const html=resolve('dist/source-mini-test.html')
  const assetRoot=pathToFileURL(resolve(process.env.QQPET_TEST_RESOURCES||'resources')+'/').href
  writeFileSync(html,'<!doctype html><html><head><meta charset="UTF-8"><base href="'+assetRoot+'"><style>'+prepared.css.replaceAll('url(/pet/','url('+assetRoot+'pet/')+'</style></head><body><div id="pet" data-hit=""></div></body></html>')
  const win=new BrowserWindow({width:800,height:560,useContentSize:true,show:false,webPreferences:{sandbox:true,contextIsolation:true,offscreen:true,backgroundThrottling:false}})
  win.webContents.on('console-message', event => { if(event.level==='error'||event.level===3) console.error('Mini fixture:',event.message) })
  const evaluate=expression=>win.webContents.executeJavaScript(expression)
  const pause=ms=>new Promise(r=>setTimeout(r,ms))
  await win.loadFile(html);await evaluate('localStorage.removeItem("qqpet.edge-mini.v1")');await evaluate(boot)
  win.webContents.debugger.attach('1.3')
  const cdp=(method,params)=>win.webContents.debugger.sendCommand(method,params)
  const move=(x,y,buttons=0)=>cdp('Input.dispatchMouseEvent',{type:'mouseMoved',x,y,button:buttons?'left':'none',buttons})
  const down=(x,y)=>cdp('Input.dispatchMouseEvent',{type:'mousePressed',x,y,button:'left',clickCount:1})
  const up=(x,y)=>cdp('Input.dispatchMouseEvent',{type:'mouseReleased',x,y,button:'left',clickCount:1})
  const drag=async(side,cancel=false)=>{
    await evaluate('fixture.position(250,200)')
    const start=await evaluate('fixture.grab()'),end=await evaluate('fixture.target('+JSON.stringify(side)+')')
    await move(start.x,start.y);await down(start.x,start.y);await move(end.x,end.y,1)
    if(cancel)await evaluate("document.getElementById('pet').dispatchEvent(new PointerEvent('pointercancel',{pointerId:1,bubbles:true}))")
    await up(end.x,end.y);await pause(50)
  }
  const results=[]
  for(const side of ['left','top','bottom','right']){
    await drag(side)
    assert.equal((await evaluate('fixture.state()')).mini,side==='right',side+' dock state')
    results.push({check:'drag-'+side,status:'passed'})
  }
  await move(0,0);await evaluate('fixture.cursor({x:0,y:0})');await pause(220)
  let state=await evaluate('fixture.state()');assert.equal(state.mode,'mini');assert.equal(state.sleepTimers,1)
  let rect=await evaluate("(()=>{const r=document.querySelector('.local-edge-mini').getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,width:r.width,height:r.height}})()")
  assert.ok(Math.abs(800-rect.x-36)<.2,'idle mini must expose half of its 72 px width')
  assert.equal(await evaluate("getComputedStyle(document.getElementById('pet')).visibility"),'hidden')
  await move(780,rect.y+40);await evaluate('fixture.cursor({x:780,y:'+String(rect.y+40)+'})');await pause(220)
  state=await evaluate('fixture.state()');assert.equal(state.mode,'peek');assert.equal(state.sleepTimers,0)
  rect=await evaluate("(()=>{const r=document.querySelector('.local-edge-mini').getBoundingClientRect();return {x:r.x,y:r.y}})()")
  assert.ok(Math.abs(800-rect.x-64)<.2,'peek must expose more of the pet')
  // A point between the enter and leave thresholds must not make peek flicker.
  await evaluate('fixture.cursor({x:700,y:'+String(rect.y+40)+'})');assert.equal((await evaluate('fixture.state()')).mode,'peek')
  await move(0,0);await evaluate('fixture.cursor({x:0,y:0});fixture.sleep()')
  assert.equal((await evaluate('fixture.state()')).mode,'mini-sleep')
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.local-mini-zzz')).display"),'block')
  await evaluate('fixture.cursor({x:780,y:'+String(rect.y+40)+'})');assert.equal((await evaluate('fixture.state()')).mode,'peek')
  await down(780,rect.y+40);await up(780,rect.y+40)
  assert.equal((await evaluate('fixture.state()')).mini,false)
  assert.equal((await evaluate('fixture.state()')).pref,null)
  assert.equal(await evaluate("getComputedStyle(document.getElementById('pet')).visibility"),'visible')
  assert.ok((await evaluate('fixture.state()')).controls,'expanding must restore usable controls')
  results.push({check:'half-body, peek hysteresis, sleep, hover wake and click expansion',status:'passed'})
  await drag('right',true);assert.equal((await evaluate('fixture.state()')).mini,false,'cancelled full drag must not dock')
  await drag('right');await move(0,0);await evaluate('fixture.cursor({x:0,y:0})');await pause(220)
  rect=await evaluate("(()=>{const r=document.querySelector('.local-edge-mini').getBoundingClientRect();return {x:r.x,y:r.y}})()")
  await down(780,rect.y+40);await move(600,rect.y+40,1);await up(600,rect.y+40)
  assert.equal((await evaluate('fixture.state()')).mini,false,'pulling the widget away must expand the pet')
  await drag('right');await move(0,0);await evaluate('fixture.cursor({x:0,y:0})');await pause(220)
  rect=await evaluate("(()=>{const r=document.querySelector('.local-edge-mini').getBoundingClientRect();return {y:r.y}})()")
  await down(780,rect.y+40);await move(780,400,1);await up(780,400)
  assert.equal((await evaluate('fixture.state()')).mini,true,'dragging along the edge must keep mini')
  assert.ok((await evaluate('fixture.state()')).y>200)
  await down(780,400);await move(600,400,1)
  await evaluate("document.querySelector('.local-edge-mini').dispatchEvent(new PointerEvent('pointercancel',{pointerId:1,bubbles:true}))")
  await up(600,400)
  assert.equal((await evaluate('fixture.state()')).mini,true);assert.equal((await evaluate('fixture.state()')).dragging,false)
  results.push({check:'full and mini drag cancellation, drag out, vertical dock drag',status:'passed'})
  await move(0,0);await evaluate('fixture.cursor({x:0,y:0});fixture.busy(true);fixture.sleep()')
  assert.equal((await evaluate('fixture.state()')).mode,'mini');assert.equal((await evaluate('fixture.state()')).sleepTimers,0)
  await evaluate('fixture.busy(false);fixture.sleep()');assert.equal((await evaluate('fixture.state()')).mode,'mini-sleep')
  await evaluate('fixture.externalPanel(true)');await pause(20);assert.equal((await evaluate('fixture.state()')).mode,'mini')
  await evaluate('fixture.externalPanel(false)');await pause(20);assert.equal((await evaluate('fixture.state()')).sleepTimers,1)
  await evaluate('fixture.hide(true)');await pause(20);assert.equal((await evaluate('fixture.state()')).hidden,true);assert.equal((await evaluate('fixture.state()')).sleepTimers,0)
  await evaluate('fixture.hide(false)');await pause(20);assert.equal((await evaluate('fixture.state()')).hidden,false)
  await evaluate('fixture.goods()');assert.equal((await evaluate('fixture.state()')).mini,false,'tray feeding must expand the pet')
  results.push({check:'busy state, dialogs, hide/show and external feeding',status:'passed'})
  const avatars=[]
  for(const sex of ['GG','MM'])for(const stage of ['Egg','Kid','Adult']){
    await evaluate('fixture.avatar('+JSON.stringify(sex)+','+JSON.stringify(stage)+');fixture.mini()')
    await evaluate("document.querySelector('.local-mini-portrait').decode()")
    assert.equal(await evaluate("document.querySelector('.local-mini-portrait').dataset.avatar"),sex+stage)
    avatars.push(sex+stage)
  }
  const layouts=[]
  for(const [w,h] of [[1920,1040],[1366,728],[800,560],[320,480]]){
    win.setContentSize(w,h);await pause(80);await evaluate('fixture.refresh();fixture.cursor({x:0,y:0})');await pause(220)
    const box=await evaluate("(()=>{const r=document.querySelector('.local-edge-mini').getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom}})()")
    assert.ok(Math.abs(w-box.x-36)<.2&&box.y>=7.5&&box.bottom<=h-7.5,'mini must remain attached and vertically inside work area')
    const state=await evaluate('fixture.state()');assert.ok(state.x>=0&&state.y>=0&&state.x<=w-146+.2&&state.y<=h-146+.2)
    layouts.push({width:w,height:h,status:'passed'})
  }
  await evaluate('fixture.health(0)');assert.equal((await evaluate('fixture.state()')).mini,false,'death must restore the full pet')
  await evaluate('fixture.health(5);fixture.mini()')
  await win.loadFile(html);await evaluate(boot)
  assert.equal((await evaluate('fixture.state()')).mini,true,'restart must restore persisted mini mode')
  win.setContentSize(480,360);await pause(80);await evaluate("fixture.avatar('GG','Kid');fixture.cursor({x:0,y:0})");await move(0,0);await pause(250)
  const capture=async(name)=>{
    const r=await evaluate("(()=>{const r=document.querySelector('.local-edge-mini').getBoundingClientRect();return {y:r.y}})()")
    writeFileSync('dist/source-mini-'+name+'-fixture.png',(await win.webContents.capturePage({x:360,y:Math.max(0,Math.floor(r.y)-12),width:120,height:104})).toPNG())
  }
  assert.ok(await evaluate("getComputedStyle(document.querySelector('.local-mini-artwork')).clipPath.includes('30%')"),'idle mini must crop the lower body');
  await capture('idle');await evaluate('fixture.cursor({x:465,y:parseFloat(document.querySelector(".local-edge-mini").style.top)+40})');await pause(450);assert.equal(await evaluate("getComputedStyle(document.querySelector('.local-mini-artwork')).animationName"),'qqpet-mini-peek');await capture('peek')
  await move(0,0);await evaluate('fixture.cursor({x:0,y:0});fixture.sleep()');await pause(250);await capture('sleep')
  await evaluate('fixture.cleanup()');assert.equal((await evaluate('fixture.state()')).sleepTimers,0)
  assert.equal((await evaluate('fixture.state()')).model.yb,5000);assert.equal((await evaluate('fixture.state()')).model.growth,0);assert.equal((await evaluate('fixture.state()')).model.health,5)
  const result={checks:results,avatarVariants:avatars,layoutCases:layouts,extraChecks:['death expands','restart restores mini','sleep timer cleaned on unload','growth, currency and health preserved'],sleepDelayMs:180000}
  writeFileSync('dist/source-mini-test-results.json',JSON.stringify(result,null,2));console.log('Edge mini passed:',JSON.stringify(result));app.exit(0)
}).catch(error=>{console.error(error);app.exit(1)})
