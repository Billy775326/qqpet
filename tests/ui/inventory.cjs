const {app,BrowserWindow,ipcMain}=require('electron')
const {readFileSync,writeFileSync,mkdtempSync,renameSync}=require('node:fs')
const {resolve,join}=require('node:path')
const {pathToFileURL}=require('node:url')
const assert=require('node:assert/strict')
const {resizeViewport}=require('./viewport.cjs')
const {startSave,applyPatch,validatedImport}=require(resolve('dist/ui-inventory-save.cjs'))
const profile=mkdtempSync(resolve('dist/inventory-profile-'))
app.setPath('userData',profile);app.setPath('sessionData',profile);app.setAppLogsPath(join(profile,'logs'))
const file=join(profile,'save.json')
let disk=startSave(null),failRename=false,writes=0
disk.havePet=true
disk.settings.quiet=true
disk.selfGoodDatas.food=['_102010001*2','_future-food*9']
disk.saveJsonData.email=JSON.stringify({'1':{d:1,l:'旧邮件',r:true,glb:[],k:'welcome'}})
writeFileSync(file,JSON.stringify(disk))
ipcMain.handle('fixture:load',()=>JSON.parse(readFileSync(file,'utf8')))
ipcMain.on('fixture:save',(event,patch)=>{
  try{
    const next=structuredClone(disk)
    applyPatch(next,patch)
    writeFileSync(file+'.tmp',JSON.stringify(next))
    if(failRename){failRename=false;throw Error('Simulated rename failure')}
    renameSync(file+'.tmp',file)
    disk=next;writes++;event.returnValue=null
  }catch(error){event.returnValue=String(error)}
})
app.whenReady().then(async()=>{
  const prepared=JSON.parse(readFileSync('dist/ui-inventory-prepared.json','utf8'))
  const assetRoot=pathToFileURL(resolve(process.env.QQPET_TEST_RESOURCES||'resources')+'/').href
  const html=resolve('dist/inventory-test.html')
  writeFileSync(html,'<!doctype html><meta charset="UTF-8"><base href="'+assetRoot+'"><style>'+prepared.css.replaceAll('url(/pet/','url('+assetRoot+'pet/')+'</style><body>')
  const win=new BrowserWindow({width:1000,height:700,useContentSize:true,show:false,webPreferences:{preload:join(__dirname,'shop-preload.cjs'),sandbox:true,contextIsolation:true,offscreen:true,backgroundThrottling:false}})
  const evaluate=code=>win.webContents.executeJavaScript(code)
  const pause=ms=>new Promise(r=>setTimeout(r,ms))
  const click=selector=>evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing '+${JSON.stringify(selector)});e.click();return true})()`)
  const boot='(async()=>{'+prepared.code+';fixture.openSetup();return true})()'
  await win.loadFile(html);await resizeViewport(win,1000,700);await evaluate(boot)
  writes=0
  const initial=JSON.stringify(disk.selfGoodDatas),seen=JSON.stringify(disk.illustrated)
  await click('.lm_once[aria-label="工具"]')
  await click('.setupAction[aria-label="全物品领取"]')
  assert.match(await evaluate("document.querySelector('.windowView').textContent"),/888/)
  await click('.windowViewBut')
  assert.equal(writes,0,'cancelling sends no mail or inventory changes')
  await click('.setupAction[aria-label="全物品领取"]')
  await evaluate("window.staleSubmit=document.querySelector('.windowViewButSubmit');true")
  const before=readFileSync(file,'utf8')
  failRename=true
  await click('.windowViewButSubmit');await pause(1100)
  assert.match(await evaluate("document.querySelector('.windowView .msg').textContent"),/保存失败/)
  assert.equal(readFileSync(file,'utf8'),before,'failed replacement leaves the real fixture save intact')
  assert.equal(writes,0)
  await click('.windowViewButSubmit')
  assert.equal(writes,1)
  assert.equal(JSON.stringify(disk.selfGoodDatas),initial)
  assert.equal(JSON.stringify(disk.illustrated),seen)
  assert.equal(await evaluate("document.querySelectorAll('.ui-window').length"),0,'sending closes the sole confirmation without a second dialog')
  assert.equal(await evaluate("document.querySelectorAll('.ui-email').length"),0,'sending does not open the mailbox')
  await evaluate('staleSubmit.click();true')
  assert.equal(writes,1,'a retained confirmation cannot send twice')
  await click('.setupAction[aria-label="全物品领取"]')
  assert.equal(await evaluate("document.querySelectorAll('.ui-window').length"),1)
  assert.match(await evaluate("document.querySelector('.windowView .msg').textContent"),/已有一封待领取/)
  await click('.windowViewButSubmit')
  assert.equal(writes,1,'the pending-mail notice only closes')
  assert.equal(await evaluate("document.querySelectorAll('.ui-window,.ui-email').length"),0,'acknowledging pending mail does not navigate')
  await evaluate('fixture.openEmail();true')
  const grantId=Object.keys(JSON.parse(disk.saveJsonData.email)).find(k=>JSON.parse(disk.saveJsonData.email)[k].l==='全物品领取')
  const row=`[data-mail-id="${grantId}"]`
  assert.equal(await evaluate(`document.querySelectorAll('${row} .e_goodImgs').length`),4,'large attachments use four representative icons')
  assert.match(await evaluate(`document.querySelector('${row} .e_attachmentSummary').textContent`),/888 种物品/)
  assert.equal(await evaluate("document.querySelectorAll('.email').length"),2,'the old email is retained')
  await evaluate("fixture.mailPhoto({id:'test-photo',city:'测试地区'});true")
  assert.equal(await evaluate("document.querySelectorAll('.email').length"),3,'an already open mailbox refreshes when new mail arrives')
  await evaluate(`window.staleClaim=document.querySelector('${row} .getEmail');true`)
  const claimBefore=readFileSync(file,'utf8'),priorWrites=writes
  failRename=true
  await click(row+' .getEmail')
  assert.equal(readFileSync(file,'utf8'),claimBefore)
  assert.equal(JSON.stringify(disk.selfGoodDatas),initial)
  assert.equal(await evaluate(`fixture.readMails()['${grantId}'].r===true`),false)
  assert.match(await evaluate("document.querySelector('.windowView .title').textContent"),/领取附件失败/)
  await click('.windowViewBut')
  await click(row+' .getEmail')
  assert.equal(writes,priorWrites+1,'all 888 attachments, illustrated IDs and claim status use one replacement')
  assert.equal(await evaluate("fixture.quantityOf('food','102010001')"),3)
  assert.ok(disk.selfGoodDatas.food.includes('_future-food*9'))
  assert.equal(JSON.parse(disk.saveJsonData.email)[grantId].r,true)
  assert.equal(Object.values(JSON.parse(disk.saveJsonData.email)).some(m=>m.p==='test-photo'),true)
  await evaluate('staleClaim.click();true')
  assert.equal(writes,priorWrites+1)
  assert.equal(JSON.parse(disk.saveJsonData.email)[grantId].e,undefined,'stale claiming never deletes the mail')
  const cases=[]
  for(const [w,h,dpr]of [[1000,700,1],[640,480,1.5],[360,640,2],[320,240,2]]){
    await resizeViewport(win,w,h,dpr)
    const rect=await evaluate(`(()=>{const r=document.querySelector('.ui-email').getBoundingClientRect();return {left:r.left,right:r.right,top:r.top,bottom:r.bottom,width:r.width}})()`)
    assert.ok(rect.left>=-1&&rect.right<=w+1&&rect.top>=-1&&rect.bottom<=h+1,JSON.stringify({w,h,rect}))
    assert.ok(rect.width>=Math.min(200,w/3),'mailbox retains readable proportions')
    cases.push({w,h,dpr})
  }
  await resizeViewport(win,1000,700,1)
  await evaluate("Promise.all([...document.querySelectorAll('.ui-email .styleBox img,.ui-email .e_goodImgs')].map(i=>i.decode())).then(()=>true)")
  writeFileSync('dist/inventory-mail.png',(await win.webContents.capturePage()).toPNG())
  await click('.ui-email .close')
  await click('.ui-setup .close')
  const original=structuredClone(disk)
  disk=validatedImport({petInfoData:JSON.parse(readFileSync(file,'utf8'))})
  assert.deepEqual(disk.selfGoodDatas,original.selfGoodDatas)
  await win.loadFile(html);await evaluate(boot)
  await evaluate('fixture.openEmail();true')
  assert.equal(await evaluate(`document.querySelector('${row} .rgetEmail').textContent`),'删除')
  await click('.getEmails')
  assert.equal(JSON.stringify(disk.selfGoodDatas),JSON.stringify(original.selfGoodDatas),'claim-all after reload cannot regrant an already claimed attachment')
  await click('.ui-email .close')
  await evaluate('fixture.openInventoryGrant();true')
  await resizeViewport(win,360,640,2)
  writeFileSync('dist/inventory-confirm.png',(await win.webContents.capturePage()).toPNG())
  writeFileSync('dist/inventory-results.json',JSON.stringify({attachments:888,singleConfirmation:true,manualMailbox:true,pendingMailNotice:true,cancel:true,atomicSend:true,atomicClaim:true,renameFailure:true,staleClicks:true,legacyImport:true,liveMailbox:true,cases},null,2))
  console.log('Inventory mail UI verified: single confirmation, manual mailbox, pending notice, 888 attachments, rollback, stale clicks, old mail, reload and four viewport combinations')
  win.destroy();app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
