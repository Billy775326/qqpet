const { app, BrowserWindow } = require('electron')
const { readFileSync, writeFileSync, mkdtempSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { pathToFileURL } = require('node:url')
const assert = require('node:assert/strict')
const profile = mkdtempSync(resolve('dist/source-edge-idle-profile-'))
app.setPath('userData', profile); app.setPath('sessionData', profile); app.setAppLogsPath(join(profile,'logs'))
app.whenReady().then(async () => {
  const prepared = JSON.parse(readFileSync('dist/ui-edge-idle-prepared.json','utf8'))
  const assetRoot = pathToFileURL(resolve(process.env.QQPET_TEST_RESOURCES || 'resources') + '/').href
  const html = resolve('dist/source-edge-idle-test.html')
  const boot = prepared.setup + '\n' + prepared.code + ';true'
  writeFileSync(html, '<html><head><base href="'+assetRoot+'"><style>'+prepared.css.replaceAll('url(/pet/','url('+assetRoot+'pet/')+'</style></head><body><div id="pet" data-hit><ruffle-player></ruffle-player><div class="face"></div></div></body></html>')
  const win = new BrowserWindow({width:800,height:560,useContentSize:true,show:false,webPreferences:{sandbox:true,offscreen:true,backgroundThrottling:false}})
  win.webContents.setAudioMuted(true)
  win.webContents.on('console-message', e => { if(e.level==='error') console.error(e.message) })
  const run = expression => win.webContents.executeJavaScript(expression.includes('await ') ? '(async()=>{'+expression+'})()' : expression)
  const state = () => run('fixture.state()')
  await win.loadFile(html); await run(boot)
  assert.equal((await state()).timers,1)
  await run("document.querySelector('.edge-idle-image').removeAttribute('src');advance(27000)")
  assert.equal((await state()).active,false,'undecoded artwork must retain the live pet')
  assert.equal(await run("getComputedStyle(document.querySelector('ruffle-player')).visibility"),'visible')
  await run("document.querySelector('.edge-idle-image').src='pet/avatar/GGKid.png'")
  await run('await fixture.step(27000)')
  assert.equal((await state()).mode,'crawl')
  assert.equal(await run("getComputedStyle(document.querySelector('ruffle-player')).visibility"),'hidden')
  await run('await fixture.step(2200)')
  let moving = await state()
  assert.ok(parseFloat(moving.translate)>0)
  assert.equal(moving.writes.length,0,'animation frames must not write the save')
  assert.equal(moving.model.lastX,200)
  await run('(()=>{const r=fixture.state().pet;fixture.cursor({x:r.x+r.width/2,y:r.y+r.height/2})})()')
  let stopped = await state()
  assert.equal(stopped.active,false,'hover must stop immediately')
  assert.equal(stopped.frames,0)
  assert.equal(stopped.timers,0)
  assert.equal(stopped.writes.length,1,'commit the interrupted position once')
  assert.equal(await run("getComputedStyle(document.querySelector('ruffle-player')).visibility"),'visible')
  await run('await fixture.step(10000)')
  assert.equal((await state()).model.lastX,stopped.model.lastX)
  await run('fixture.cursor({x:-100,y:-100});roll=.75;fixture.position();await fixture.step(40000)')
  assert.equal((await state()).mode,'rest')
  await run("document.body.dispatchEvent(new PointerEvent('pointerdown',{bubbles:true}))")
  assert.equal((await state()).active,false,'press must stop before other click handlers run')
  const blockers=['busy','paused','hidden','sick','dead','mini','visibility','pose']
  for (const name of blockers) {
    await run(`fixture.block(${JSON.stringify(name)},true);await fixture.step(60000)`)
    assert.equal((await state()).active,false,name+' must block idle animation')
    assert.equal((await state()).timers,0,name+' must cancel waiting timers')
    await run(`fixture.block(${JSON.stringify(name)},false)`)
  }
  await run('fixture.panel(true)')
  assert.equal((await state()).timers,0,'dialogs must pause idle animation')
  await run('fixture.panel(false);fixture.reduced(true);await fixture.step(60000)')
  assert.equal((await state()).active,false)
  await run('fixture.reduced(false);fixture.boundary(false)')
  await run('fixture.refresh();await fixture.step(60000)')
  assert.equal((await state()).active,false,'bare screen edges must not act like taskbars')
  await run('fixture.boundary(true)')
  await run('fixture.position(200,150);await fixture.step(60000)')
  assert.equal((await state()).active,false,'moving away from the taskbar must disable idle animation')
  const cases=[]
  for (const [width,height] of [[320,480],[800,560],[1920,1040]]) {
    win.setContentSize(width,height)
    await run('fixture.boundary(true)')
    for (const sex of ['GG','MM']) for (const phase of ['Egg','Kid','Adult']) for (const x of [0,width-146]) {
      await run(`roll=.25;fixture.avatar('${sex}','${phase}');fixture.position(${x});await fixture.step(27000)`)
      assert.equal((await state()).mode,'crawl')
      await run("document.querySelector('.edge-idle-image').decode()")
      await run('await fixture.step(2200)')
      const s=await state()
      assert.equal(s.portrait,sex+phase)
      assert.ok(s.art.x>=-0.5&&s.art.right<=width+.5&&s.art.bottom<=height+.5,'portrait must stay inside the work area: '+JSON.stringify(s.art))
      assert.equal(s.model.yb,5000)
      assert.equal(s.model.health,5)
      assert.equal(s.model.growth,0)
      await run('await fixture.step(2300)')
      assert.equal((await state()).active,false,'finished motion must restore the normal pet')
      cases.push({width,height,sex,phase,x})
    }
  }
  win.setContentSize(640,360)
  await run("fixture.boundary(true)")
  await run("roll=.25;fixture.avatar('GG','Kid');fixture.position(200);await fixture.step(27000);await fixture.step(1800)")
  writeFileSync('dist/edge-crawl-preview.png',(await win.webContents.capturePage()).toPNG())
  await run('roll=.75;fixture.position(200);await fixture.step(40000)')
  writeFileSync('dist/edge-rest-preview.png',(await win.webContents.capturePage()).toPNG())
  await run('fixture.destroy()')
  assert.equal(await run('timers.size+frames.size'),0,'unload must release timers and animation frames')
  assert.equal(await run("document.querySelectorAll('.edge-idle').length"),0)
  writeFileSync('dist/source-edge-idle-results.json',JSON.stringify({cases:cases.length,blockers,checks:['hover and press interrupt','single save on completion or interruption','real bottom taskbar only','normal SWF restored','reduced motion','unload cleanup','model preserved'],results:cases},null,2))
  // The generated preview must work under file:// without same-origin iframe access.
  {
    win.setContentSize(1100,1100)
    await win.loadFile(resolve('dist/edge-motion-preview.html'))
    const preview = expression => win.webContents.executeJavaScript(expression)
    const waitMode = async text => {
      for (let attempt=0;attempt<30;attempt++) {
        if (await preview(`document.getElementById('state').textContent === ${JSON.stringify(text)}`)) return
        await new Promise(done=>setTimeout(done,50))
      }
      assert.fail('Preview failed to enter '+text)
    }
    await preview("document.querySelectorAll('button')[0].click()")
    await waitMode('正在爬行')
    await preview("document.querySelectorAll('button')[1].click()")
    await waitMode('正在趴卧')
    writeFileSync('dist/edge-motion-preview.png',(await win.webContents.capturePage()).toPNG())
  }
  console.log('Taskbar idle passed:',cases.length,'layout/avatar cases, interruptions, blockers and cleanup')
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
