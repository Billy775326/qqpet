const {app,BrowserWindow,ipcMain}=require('electron')
const {readFileSync,writeFileSync,mkdtempSync,renameSync,symlinkSync,unlinkSync,lstatSync}=require('node:fs')
const {resolve,join}=require('node:path')
const {pathToFileURL}=require('node:url')
const assert=require('node:assert/strict')
const {resizeViewport}=require('./viewport.cjs')
const {startSave,applyPatch}=require(resolve('dist/ui-fishing-save.cjs'))
const root=mkdtempSync(resolve('dist/fishing-native-'))
app.setPath('userData',join(root,'profile'));app.setPath('sessionData',join(root,'profile'));app.setAppLogsPath(join(root,'logs'))
const file=join(root,'save.json')
let disk=startSave(null),stockCommits=0,failStock=false
disk.havePet=true;disk.petInfo.yb=20;disk.settings.quiet=true
writeFileSync(file,JSON.stringify(disk))
symlinkSync(resolve(process.env.QQPET_TEST_RESOURCES||'resources','pet'),join(root,'pet'),'junction')
app.on('will-quit',()=>{assert.ok(lstatSync(join(root,'pet')).isSymbolicLink());unlinkSync(join(root,'pet'))})
ipcMain.handle('fixture:load',()=>structuredClone(disk))
ipcMain.on('fixture:save',(event,patch)=>{
  try{
    const next=structuredClone(disk);applyPatch(next,patch)
    const stock=patch.petInfo?.yb!==undefined&&patch.saveJsonData?.fishs!==undefined
    writeFileSync(file+'.tmp',JSON.stringify(next))
    if(stock&&failStock){failStock=false;throw Error('Simulated stocking save failure')}
    renameSync(file+'.tmp',file);disk=next
    if(stock)stockCommits++
    event.returnValue=null
  }catch(error){event.returnValue=String(error)}
})
app.whenReady().then(async()=>{
  const prepared=JSON.parse(readFileSync('dist/ui-fishing-prepared.json','utf8'))
  const html=join(root,'index.html'),ruffle=pathToFileURL(resolve('out/renderer/ruffle/ruffle.js')).href,base=pathToFileURL(root+'/').href
  writeFileSync(html,'<!doctype html><meta charset="UTF-8"><script src="'+ruffle+'"></script><style>'+prepared.css.replaceAll('url(/pet/','url('+base+'pet/')+'</style><body>')
  const win=new BrowserWindow({width:800,height:600,useContentSize:true,show:false,webPreferences:{preload:join(__dirname,'shop-preload.cjs'),sandbox:true,contextIsolation:true,offscreen:true,backgroundThrottling:false}})
  win.webContents.on('console-message',event=>{if(event.level==='error'||event.level===3||/Error|Exception/.test(event.message||''))console.log('Pond renderer:',event.message.slice(0,1200))})
  win.webContents.setAudioMuted(true)
  const evaluate=code=>win.webContents.executeJavaScript(code)
  const pause=ms=>new Promise(r=>setTimeout(r,ms))
  const click=selector=>evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing '+${JSON.stringify(selector)});e.click();return true})()`)
  const flashClick=async(x,y)=>{
    const point=await evaluate(`(()=>{const r=document.querySelector('ruffle-player').getBoundingClientRect();return{x:r.x+r.width*${x}/411,y:r.y+r.height*${y}/320}})()`)
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
    await pause(100)
    for(const type of ['mousePressed','mouseReleased'])await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type,...point,button:'left',clickCount:1})
    await pause(100)
  }
  const wait=async(expression,limit=25000)=>{const until=Date.now()+limit;while(Date.now()<until){if(await evaluate(expression))return;await pause(100)}throw Error('Timed out: '+expression)}
  const fish=()=>JSON.parse(disk.saveJsonData.fishs||'{}').fishs||[]
  await win.loadFile(html);await resizeViewport(win,800,600)
  await evaluate('(async()=>{'+prepared.code+';fixture.openFishing();return true})()')
  await wait("Boolean(document.querySelector('ruffle-player')?.PETEventOnReceived)")
  await pause(2000)
  writeFileSync('dist/fishing-start.png',(await win.webContents.capturePage()).toPNG())
  await flashClick(200,160)
  await flashClick(24,149)
  await pause(300)
  writeFileSync('dist/fishing-shop.png',(await win.webContents.capturePage()).toPNG())
  // The native shop initially selects the first eligible fry; clicking it toggles it off.
  await flashClick(205,265)
  writeFileSync('dist/fishing-payment-confirm.png',(await win.webContents.capturePage()).toPNG())
  await flashClick(180,190)
  await wait("Boolean(document.querySelector('.chooseNum'))",2000)
  assert.equal(await evaluate("document.querySelector('.chooseNum .content').textContent"),'1')
  assert.match(await evaluate("document.querySelector('.windowView .msg').textContent"),/合计 2 元宝/)
  assert.equal(await evaluate("document.querySelector('ruffle-player').ruffle().isPlaying"),false,'the movie waits while choosing quantity')
  await evaluate("window.cancelledPondSubmit=document.querySelector('.windowViewButSubmit');true")
  await click('.windowViewBut')
  await evaluate('cancelledPondSubmit.click();true')
  await pause(100)
  assert.equal(fish().length,0);assert.equal(disk.petInfo.yb,20)
  assert.equal(await evaluate("document.querySelector('ruffle-player').ruffle().isPlaying"),true)
  await flashClick(225,176)
  await evaluate('fixture.purchase();true')
  await click('.quantityButton.add')
  assert.equal(await evaluate("document.querySelector('.chooseNum .content').textContent"),'2')
  assert.match(await evaluate("document.querySelector('.windowView .msg').textContent"),/合计 4 元宝/,'total cost updates in the same click')
  await pause(50)
  writeFileSync('dist/fishing-quantity.png',(await win.webContents.capturePage()).toPNG())
  await evaluate("fixture.setInfo('yb',3);true")
  await click('.windowViewButSubmit')
  assert.equal(fish().length,0,'a reduced live limit needs review before confirmation')
  assert.equal(disk.petInfo.yb,3)
  await click('.windowViewButSubmit')
  await pause(300)
  assert.equal(fish().length,1);assert.equal(disk.petInfo.yb,1);assert.equal(stockCommits,1)
  await evaluate("fixture.setInfo('yb',20);fixture.purchase();true")
  await click('.quantityButton.add')
  await evaluate("window.stalePondSubmit=document.querySelector('.windowViewButSubmit');true")
  const previous=readFileSync(file,'utf8')
  failStock=true
  await click('.windowViewButSubmit');await pause(1100)
  assert.match(await evaluate("document.querySelector('.windowView .msg').textContent"),/保存失败/)
  assert.equal(readFileSync(file,'utf8'),previous)
  assert.equal(fish().length,1);assert.equal(disk.petInfo.yb,20)
  const cases=[]
  for(const [w,h,dpr]of [[800,600,1],[640,480,1.5],[320,240,2]]){
    await resizeViewport(win,w,h,dpr)
    const r=await evaluate("(()=>{const r=document.querySelector('.ui-window').closest('.boxFrame').getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom}})()")
    assert.ok(r.x>=-1&&r.y>=-1&&r.right<=w+1&&r.bottom<=h+1)
    cases.push({w,h,dpr})
  }
  await resizeViewport(win,800,600)
  await click('.windowViewButSubmit');await pause(500)
  assert.equal(fish().length,3);assert.equal(disk.petInfo.yb,16);assert.equal(stockCommits,2)
  assert.equal(new Set(fish().map(f=>f.id)).size,3)
  await evaluate('stalePondSubmit.click();true')
  assert.equal(stockCommits,2)
  await pause(2000)
  writeFileSync('dist/fishing-stocked.png',(await win.webContents.capturePage()).toPNG())
  await evaluate("window.close_game(1);fixture.setInfo('pinkDiamond',true);fixture.setInfo('yb',1000);fixture.openFishing();true")
  await wait("Boolean(document.querySelector('ruffle-player')?.PETEventOnReceived)")
  await evaluate('fixture.purchase();true')
  await click('.quantityButton.add')
  assert.equal(await evaluate("document.querySelector('.chooseNum .content').textContent"),'2','VIP can fill the remaining two of five positions')
  await evaluate('window.close_game(1);true')
  assert.equal(await evaluate("document.querySelectorAll('.ui-window,.ui-fishing').length"),0,'closing the pond cancels its unconfirmed picker')
  assert.equal(disk.petInfo.yb,1000);assert.equal(fish().length,3);assert.equal(stockCommits,2)
  await evaluate('fixture.openFishing();true')
  await wait("Boolean(document.querySelector('ruffle-player')?.PETEventOnReceived)")
  await evaluate('fixture.purchase();true')
  await click('.quantityButton.add')
  await click('.windowViewButSubmit');await pause(300)
  assert.equal(fish().length,5);assert.equal(stockCommits,3)
  await evaluate('window.close_game(1);fixture.openFishing();window.close_game(1);true')
  assert.equal(await evaluate("document.querySelectorAll('.ui-window,.ui-fishing').length"),0)
  await pause(200)
  assert.equal(stockCommits,3)
  writeFileSync('dist/fishing-results.json',JSON.stringify({realRuffle:true,nativePurchaseEntry:true,ordinaryCapacity:3,vipCapacity:5,stockCommits,defaultOne:true,liveLimit:true,atomicFailure:true,staleClicks:true,cancel:true,pendingClose:true,earlyClose:true,cases},null,2))
  console.log('Real pond UI verified: quantity, current limits, save failure/retry, 3/5 capacity, distinct IDs, cancel, stale callbacks and closing during load')
  win.destroy();app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
