const {app,BrowserWindow,ipcMain}=require('electron')
const {readFileSync,writeFileSync,mkdtempSync,renameSync,symlinkSync,unlinkSync,lstatSync}=require('node:fs')
const {resolve,join}=require('node:path')
const {pathToFileURL}=require('node:url')
const assert=require('node:assert/strict')
const {resizeViewport}=require('./viewport.cjs')
const {startSave,applyPatch}=require(resolve('dist/ui-fishing-save.cjs'))
const root=mkdtempSync(resolve('dist/fishing-native-'))
app.setPath('userData',join(root,'profile'));app.setPath('sessionData',join(root,'profile'));app.setAppLogsPath(join(root,'logs'))
const file=join(root,'save.json')
let disk=startSave(null),stockCommits=0,failStock=false
disk.havePet=true;disk.petInfo.yb=20;disk.settings.quiet=true
writeFileSync(file,JSON.stringify(disk))
symlinkSync(resolve(process.env.QQPET_TEST_RESOURCES||'resources','pet'),join(root,'pet'),'junction')
app.on('will-quit',()=>{assert.ok(lstatSync(join(root,'pet')).isSymbolicLink());unlinkSync(join(root,'pet'))})
ipcMain.handle('fixture:load',()=>structuredClone(disk))
ipcMain.on('fixture:save',(event,patch)=>{
  try{
    const next=structuredClone(disk);applyPatch(next,patch)
    const stock=patch.petInfo?.yb!==undefined&&patch.saveJsonData?.fishs!==undefined
    writeFileSync(file+'.tmp',JSON.stringify(next))
    if(stock&&failStock){failStock=false;throw Error('Simulated stocking save failure')}
    renameSync(file+'.tmp',file);disk=next
    if(stock)stockCommits++
    event.returnValue=null
  }catch(error){event.returnValue=String(error)}
})
app.whenReady().then(async()=>{
  const prepared=JSON.parse(readFileSync('dist/ui-fishing-prepared.json','utf8'))
  const html=join(root,'index.html'),ruffle=pathToFileURL(resolve('out/renderer/ruffle/ruffle.js')).href,base=pathToFileURL(root+'/').href
  writeFileSync(html,'<!doctype html><meta charset="UTF-8"><script src="'+ruffle+'"></script><style>'+prepared.css.replaceAll('url(/pet/','url('+base+'pet/')+'</style><body>')
  const win=new BrowserWindow({width:800,height:600,useContentSize:true,show:false,webPreferences:{preload:join(__dirname,'shop-preload.cjs'),sandbox:true,contextIsolation:true,offscreen:true,backgroundThrottling:false}})
  const runtimeErrors=[]
  win.webContents.on('console-message',event=>{if(/Error #|TypeError|ReferenceError|VerifyError/.test(event.message||''))runtimeErrors.push(event.message);if(event.level==='error'||event.level===3||/Error|Exception/.test(event.message||''))console.log('Pond renderer:',event.message.slice(0,1200))})
  win.webContents.setAudioMuted(true)
  const evaluate=code=>win.webContents.executeJavaScript(code)
  const pause=ms=>new Promise(r=>setTimeout(r,ms))
  const flashClick=async(x,y)=>{
    const point=await evaluate(`(()=>{const r=document.querySelector('ruffle-player').getBoundingClientRect();return{x:r.x+r.width*${x}/411,y:r.y+r.height*${y}/320}})()`)
    await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type:'mouseMoved',...point})
    await pause(100)
    for(const type of ['mousePressed','mouseReleased'])await win.webContents.debugger.sendCommand('Input.dispatchMouseEvent',{type,...point,button:'left',clickCount:1})
    await pause(100)
  }
  const wait=async(expression,limit=25000)=>{const until=Date.now()+limit;while(Date.now()<until){if(await evaluate(expression))return;await pause(100)}throw Error('Timed out: '+expression)}
  const fish=()=>JSON.parse(disk.saveJsonData.fishs||'{}').fishs||[]
  const attach=()=>evaluate(`(()=>{const send=window.PETSendData;window.PETSendData=json=>{const message=JSON.parse(json);if(message.head.cmd===4)window.stockRequests.push(message.data);send(json)};return true})()`)
  const requests=()=>evaluate('stockRequests')
  const noExtraWindow=async()=>assert.equal(await evaluate("document.querySelectorAll('.ui-window,.chooseNum').length"),0,'quantity belongs to the native selection screen')
  const pay=()=>flashClick(321,256)
  const confirm=()=>flashClick(180,180)
  const add=()=>flashClick(179,228)
  const minus=()=>flashClick(132,228)
  const shop=async()=>{await flashClick(24,149);await pause(150)}
  await win.loadFile(html);await resizeViewport(win,800,600)
  await evaluate('(async()=>{'+prepared.code+';window.stockRequests=[];window.previousQuote=()=>({sentinel:true});window.QQPetPondStockQuote=previousQuote;fixture.openFishing();return true})()')
  await attach()
  await wait("Boolean(document.querySelector('ruffle-player')?.PETEventOnReceived)")
  await pause(2000)
  writeFileSync('dist/fishing-start.png',(await win.webContents.capturePage()).toPNG())
  await flashClick(200,160)
  await shop()
  await pause(300)
  writeFileSync('dist/fishing-shop.png',(await win.webContents.capturePage()).toPNG())
  await noExtraWindow()
  assert.equal(await evaluate("document.querySelector('ruffle-player').ruffle().isPlaying"),true)
  await add();await add();await add() // The third click is disabled at the ordinary cap.
  await pay()
  writeFileSync('dist/fishing-payment-confirm.png',(await win.webContents.capturePage()).toPNG())
  await flashClick(255,180) // Cancel the one original payment confirmation.
  assert.equal((await requests()).length,0)
  assert.equal(fish().length,0);assert.equal(disk.petInfo.yb,20)
  await minus();await pay()
  await confirm();await confirm();await pause(300)
  assert.equal((await requests()).length,1)
  assert.equal((await requests())[0].count,2,'the native minus button edits the same inline quantity')
  assert.equal(fish().length,2);assert.equal(disk.petInfo.yb,16);assert.equal(stockCommits,1)
  assert.equal(new Set(fish().map(f=>f.id)).size,2)
  await noExtraWindow()
  await shop();await add();await pay()
  failStock=true
  const previous=readFileSync(file,'utf8')
  await confirm();await pause(300)
  assert.equal(readFileSync(file,'utf8'),previous)
  assert.equal(fish().length,2);assert.equal(disk.petInfo.yb,16)
  assert.equal((await requests()).at(-1).count,1,'one remaining position caps quantity')
  await noExtraWindow()
  writeFileSync('dist/fishing-save-failure.png',(await win.webContents.capturePage()).toPNG())
  await flashClick(225,175) // Dismiss the original error dialog, then retry.
  writeFileSync('dist/fishing-quantity.png',(await win.webContents.capturePage()).toPNG())
  const cases=[]
  for(const [w,h,dpr]of [[800,600,1],[640,480,1.5],[320,240,2]]){
    await resizeViewport(win,w,h,dpr)
    const r=await evaluate("(()=>{const r=document.querySelector('.ui-fishing').closest('.boxFrame').getBoundingClientRect();return {x:r.x,y:r.y,right:r.right,bottom:r.bottom}})()")
    assert.ok(r.x>=-1&&r.y>=-1&&r.right<=w+1&&r.bottom<=h+1)
    await noExtraWindow()
    writeFileSync('dist/fishing-inline-'+w+'.png',(await win.webContents.capturePage()).toPNG())
    cases.push({w,h,dpr})
  }
  await resizeViewport(win,800,600)
  await pay();await confirm();await pause(300)
  assert.equal(fish().length,3);assert.equal(disk.petInfo.yb,14);assert.equal(stockCommits,2)
  assert.equal(new Set(fish().map(f=>f.id)).size,3)
  await shop();await add();await pay();await pause(150)
  assert.equal(stockCommits,2,'a full ordinary pond cannot buy more fish')
  await noExtraWindow()
  writeFileSync('dist/fishing-stocked.png',(await win.webContents.capturePage()).toPNG())
  await evaluate("window.close_game(1);fixture.setInfo('pinkDiamond',true);fixture.setInfo('yb',1000);fixture.openFishing();true")
  await attach()
  await wait("Boolean(document.querySelector('ruffle-player')?.PETEventOnReceived)")
  await pause(1500);await flashClick(200,160);await shop();await add();await pay()
  await evaluate("fixture.setInfo('yb',3);true")
  await confirm();await pause(200)
  assert.equal((await requests()).at(-1).count,2)
  assert.equal(fish().length,3);assert.equal(stockCommits,2,'a stale balance rejects the entire confirmed batch')
  assert.equal(disk.petInfo.yb,3)
  await flashClick(225,175)
  await evaluate("fixture.setInfo('yb',1000);true")
  await pause(600);await add();await pay()
  await evaluate('window.close_game(1);true')
  assert.equal(await evaluate("document.querySelectorAll('.ui-window,.ui-fishing').length"),0,'closing cancels the native payment confirmation')
  assert.equal(await evaluate('window.QQPetPondStockQuote===previousQuote'),true,'the native quote bridge is restored')
  assert.equal(disk.petInfo.yb,1000);assert.equal(fish().length,3);assert.equal(stockCommits,2)
  await evaluate('fixture.openFishing();true')
  await attach()
  await wait("Boolean(document.querySelector('ruffle-player')?.PETEventOnReceived)")
  await pause(1500);await flashClick(200,160);await shop()
  // Deselect/reselect resets quantity; repeated + clicks stop at the live cap.
  await add();await flashClick(130,170);await flashClick(130,170)
  await pay();await confirm();await pause(300)
  assert.equal((await requests()).at(-1).count,1,'changing the fish selection resets to one')
  assert.equal(fish().length,4);assert.equal(stockCommits,3)
  await shop();await add();await pay();await confirm();await pause(300)
  assert.equal((await requests()).at(-1).count,1)
  assert.equal(fish().length,5);assert.equal(stockCommits,4)
  await evaluate('window.close_game(1);fixture.openFishing();window.close_game(1);true')
  assert.equal(await evaluate("document.querySelectorAll('.ui-window,.ui-fishing').length"),0)
  await pause(200)
  assert.equal(stockCommits,4)
  assert.deepEqual(runtimeErrors,[],'native controls must not introduce ActionScript runtime errors')
  writeFileSync('dist/fishing-results.json',JSON.stringify({realRuffle:true,nativePurchaseEntry:true,inlineQuantity:true,extraQuantityWindow:false,ordinaryCapacity:3,vipCapacity:5,stockCommits,defaultOne:true,liveLimit:true,atomicFailure:true,duplicateConfirm:true,cancel:true,pendingClose:true,earlyClose:true,cases,requests:await requests()},null,2))
  console.log('Real pond UI verified: inline quantity without extra windows, native payment/cancel, live limits, atomic retry, 3/5 capacity, duplicate confirm, selection reset, bridge cleanup and close during load')
  win.destroy();app.quit()
}).catch(error=>{console.error(error);app.exit(1)})
