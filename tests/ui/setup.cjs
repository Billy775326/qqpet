const {app,BrowserWindow,ipcMain}=require('electron')
const {readFileSync,writeFileSync,mkdtempSync}=require('node:fs')
const {resolve,join}=require('node:path')
const assert=require('node:assert/strict')
const {resizeViewport}=require('./viewport.cjs')
const profile=mkdtempSync(resolve('dist/setup-profile-'))
app.setPath('userData',profile);app.setPath('sessionData',profile);app.setAppLogsPath(join(profile,'logs'))
const settings={hd:false,opacity:1,faceClick:0,quiet:false,clip:false,aiUrl:'https://fixture.example/v1',aiKey:'fixture-key',aiModel:'',weatherCity:''}
const disk={petInfo:{yb:5000,sex:'GG',growth:0,faceClick:0,health:5,lastX:100,lastY:100},settings,petComputedlInfo:{level:1},selfGoodDatas:{food:[],clean:[],medicine:[],toy:[],nums:[],background:[]},selfGoodUseOption:{background:null}}
let writes=0,questions=0,resets=0,imports=0,exportCalls=0,modelCalls=0,chatCalls=0,resolveModels,rejectModels,resolveChat,lastConfig
let failNextSave=false
ipcMain.handle('fixture:load',()=>structuredClone(disk))
ipcMain.on('fixture:save',(event,patch)=>{if(failNextSave){failNextSave=false;event.returnValue='Simulated fixture save failure';return}for(const [key,value]of Object.entries(patch))Object.assign(disk[key],value);writes++;event.returnValue=null})
ipcMain.handle('fixture:question',()=>{questions++;return 0})
ipcMain.handle('fixture:export',()=>{exportCalls++;return false})
ipcMain.on('fixture:import',()=>imports++)
ipcMain.on('fixture:reset',()=>resets++)
ipcMain.handle('fixture:models',(_event,config)=>{modelCalls++;lastConfig=config;return new Promise((resolve,reject)=>{resolveModels=resolve;rejectModels=reject})})
ipcMain.handle('fixture:chat',()=>{chatCalls++;return new Promise(resolve=>{resolveChat=resolve})})
app.whenReady().then(async()=>{
  const prepared=JSON.parse(readFileSync('dist/ui-shop-prepared.json','utf8'))
  const assetRoot=require('node:url').pathToFileURL(resolve(process.env.QQPET_TEST_RESOURCES||'resources')+'/').href
  const html=resolve('dist/setup-test.html')
  writeFileSync(html,'<!doctype html><head><meta charset="utf-8"><base href="'+assetRoot+'"><style>'+prepared.css.replaceAll('url(/pet/','url('+assetRoot+'pet/')+'</style></head><body></body>')
  const win=new BrowserWindow({width:1000,height:700,useContentSize:true,show:false,webPreferences:{preload:join(__dirname,'setup-preload.cjs'),sandbox:true,contextIsolation:true,offscreen:true,backgroundThrottling:false}})
  const evaluate=code=>win.webContents.executeJavaScript(code)
  const pause=ms=>new Promise(r=>setTimeout(r,ms))
  await win.loadFile(html);await resizeViewport(win,1000,700);await evaluate('(async()=>{'+prepared.code+';fixture.openSetup()})()')
  const cdp=(method,params)=>win.webContents.debugger.sendCommand(method,params)
  const click=async selector=>{
    const point=await evaluate(`(()=>{const e=document.querySelector(${JSON.stringify(selector)});if(!e)throw Error('Missing '+${JSON.stringify(selector)});e.scrollIntoView({block:'nearest'});const r=e.getBoundingClientRect();return {x:r.x+r.width/2,y:r.y+r.height/2}})()`)
    for(const type of ['mouseMoved','mousePressed','mouseReleased'])await cdp('Input.dispatchMouseEvent',{type,...point,button:type==='mouseMoved'?'none':'left',clickCount:1})
    await pause(35)
  }
  const tab=name=>click('.lm_once[aria-label="'+name+'"]')
  const action=name=>click('.setupAction[aria-label="'+name+'"]')
  const edit=async(label,value)=>{await click('input[aria-label="'+label+'"]');await evaluate(`document.querySelector('input[aria-label="${label}"]').select()`);await cdp('Input.insertText',{text:value})}
  assert.equal(await evaluate("document.querySelectorAll('.setupAction.danger').length"),0,'destructive actions belong in the save tab')
  assert.equal(await evaluate("document.querySelector('.setupAction').textContent"),'召回宠物')
  assert.equal(await evaluate("getComputedStyle(document.querySelector('.setupAction')).opacity"),'1','actions must be visible without hovering')
  await click('[aria-label="免打扰模式"] .label');assert.equal(settings.quiet,true,'clicking the label toggles the whole row')
  const scroll=await evaluate("document.querySelector('.rightScroll').scrollTop")
  await evaluate("document.querySelector('[aria-label=\"免打扰模式\"]').dispatchEvent(new KeyboardEvent('keydown',{key:' '}))")
  assert.equal(settings.quiet,false);assert.equal(await evaluate("document.querySelector('.rightScroll').scrollTop"),scroll,'updates preserve scroll position')
  assert.equal(await evaluate("document.activeElement.getAttribute('aria-label')"),'免打扰模式','redraw keeps keyboard focus on the same control')
  await click('[aria-label="降低透明度"]');assert.equal(settings.opacity,.9)
  await click('[aria-label="提高透明度"]');assert.equal(settings.opacity,1)
  assert.equal(await evaluate("document.querySelector('.sliderValue').textContent"),'100%')
  await tab('存档');await action('导出存档');assert.equal(exportCalls,1)
  await action('导入存档');assert.equal(questions,1);assert.equal(imports,0)
  await action('更换性别并重生');assert.equal(questions,2);assert.equal(resets,0,'cancelling the existing confirmation preserves the pet')
  await tab('工具');await click('[aria-label="播报复制的文字"] .label');assert.equal(settings.clip,true)
  await tab('AI');assert.equal(await evaluate("document.querySelector('input[aria-label=\"API Key\"]').type"),'password')
  await edit('接口地址','https://other-fixture.example/v1')
  await action('获取模型列表')
  assert.equal(modelCalls,1,'a single click after editing must also commit the field and start the request')
  assert.equal(lastConfig.url,'https://other-fixture.example/v1');assert.equal(lastConfig.key,'','changing endpoint clears the saved key')
  await click('.setupAction.disabled');assert.equal(modelCalls,1,'busy requests cannot be repeated')
  resolveModels(['fixture-model-with-a-very-long-name-that-must-wrap-without-horizontal-overflow']);await pause(80)
  failNextSave=true
  await click('.childrenIn[role=radio]')
  assert.equal(chatCalls,0,'a failed initial save must not start a model request')
  assert.ok(await evaluate("document.querySelector('.rightScroll').textContent.includes('测试失败')"))
  assert.equal(await evaluate("document.querySelectorAll('.setupAction.disabled').length"),0,'save failure must release the busy state')
  await click('.childrenIn[role=radio]');assert.equal(chatCalls,1)
  resolveChat('隔离测试回复');await pause(80);assert.ok(settings.aiModel.startsWith('fixture-model'))
  await action('关闭 AI');assert.equal(settings.aiModel,'')
  await action('获取模型列表');const staleResolve=resolveModels
  await edit('接口地址','https://third-fixture.example/v1');await tab('工具');await tab('AI')
  staleResolve(['stale-model']);await pause(80)
  assert.equal(await evaluate("document.querySelectorAll('.childrenIn[role=radio]').length"),0,'stale results cannot replace a changed endpoint')
  await action('获取模型列表');resolveModels(['pending-test-model']);await pause(80)
  await click('.childrenIn[role=radio]');assert.equal(chatCalls,2)
  await edit('接口地址','https://final-fixture.example/v1');await tab('工具');await tab('AI')
  resolveChat('旧接口的延迟回复');await pause(80)
  assert.equal(settings.aiModel,'','a stale test cannot enable AI for another endpoint')
  await action('获取模型列表');rejectModels(new Error('隔离测试连接失败'));await pause(80)
  assert.ok(await evaluate("document.querySelector('.rightScroll').textContent.includes('获取失败')"))
  await action('获取模型列表');resolveModels(['save-failure-model']);await pause(80)
  await click('.childrenIn[role=radio]')
  failNextSave=true;resolveChat('模拟保存失败前的正常回复');await pause(80)
  assert.equal(settings.aiModel,'','a failed model-enable save must leave persisted AI disabled')
  assert.equal(await evaluate('fixture.settings().aiModel'),'','renderer state must agree with the persisted disabled model')
  assert.ok(await evaluate("document.querySelector('.rightScroll').textContent.includes('测试失败')"))
  const layouts=[]
  for(const [width,height]of [[1920,1040],[1000,700],[800,560],[480,360],[320,480]]){
    await resizeViewport(win,width,height)
    for(const name of ['全局设置','存档','工具','AI','关于']){
      await tab(name)
      const state=await evaluate(`(()=>{const e=document.querySelector('.ui-setup'),r=e.getBoundingClientRect(),panel=e.querySelector('.rightScroll');return {x:r.x,y:r.y,right:r.right,bottom:r.bottom,scroll:panel.scrollWidth,client:panel.clientWidth,footer:getComputedStyle(panel).bottom,frame:getComputedStyle(e.closest('.backgroundImage')).borderImageSource}})()`)
      assert.ok(state.x>=7.5&&state.y>=7.5&&state.right<=width-7.5&&state.bottom<=height-7.5,'settings must stay inside the viewport')
      assert.ok(state.scroll<=state.client+1,'settings text must wrap instead of overflowing horizontally')
      assert.ok(state.frame.includes('sysSeting/ditu.png'),'retain the original settings skin')
      assert.equal(state.footer,'26px','content must end at the frame border without reserving the removed button footer')
      assert.ok(await evaluate("(async()=>{const image=new Image();image.src=getComputedStyle(document.querySelector('.setupFrame .backgroundImage')).borderImageSource.slice(5,-2);await image.decode();return image.naturalWidth>0})()"),'settings artwork must actually load')
      assert.equal(await evaluate("document.querySelectorAll('.lm_once[aria-selected=true]').length"),1)
      layouts.push({width,height,tab:name,status:'passed'})
    }
  }
  await resizeViewport(win,1000,700);await tab('全局设置');writeFileSync('dist/setup-global.png',(await win.webContents.capturePage()).toPNG())
  const footerGap=await evaluate(`(()=>{const panel=document.querySelector('.rightScroll');panel.scrollTop=panel.scrollHeight;const last=panel.querySelector('.setupFootnote').getBoundingClientRect(),rect=panel.getBoundingClientRect();return (rect.bottom-last.bottom)*panel.clientHeight/rect.height})()`)
  assert.ok(footerGap>=0&&footerGap<=6,'the final save hint must reach the end without empty scroll rows')
  writeFileSync('dist/setup-global-bottom.png',(await win.webContents.capturePage()).toPNG())
  await tab('AI');writeFileSync('dist/setup-ai.png',(await win.webContents.capturePage()).toPNG())
  await action('获取模型列表');await evaluate("document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}))")
  resolveModels(['closed-result']);await pause(80);assert.equal(await evaluate("document.querySelectorAll('.ui-setup').length"),0)
  await evaluate('fixture.openSetup();fixture.openSetup()');assert.equal(await evaluate("document.querySelectorAll('.ui-setup').length"),1)
  const before=writes;await click('[aria-label="免打扰模式"] .label');assert.equal(writes,before+1,'reopening must not duplicate listeners')
  await edit('天气城市','上海')
  await evaluate("document.dispatchEvent(new KeyboardEvent('keydown',{key:'Escape'}))");assert.equal(await evaluate("document.querySelectorAll('.ui-setup').length"),0)
  assert.equal(settings.weatherCity,'上海','closing the settings commits the focused input')
  writeFileSync('dist/setup-results.json',JSON.stringify({layouts,checks:['visible actions','whole-row and keyboard toggles','scroll position retained','opacity controls','cancelled import and reset','masked key','input blur preserves the first button click','busy guard','model test enables AI','stale request ignored','failure feedback','Escape and repeated-open cleanup'],modelCalls,chatCalls},null,2))
  console.log('Settings passed: 25 viewport/tab combinations, normal actions, input commit, AI request states, confirmations and lifecycle')
  app.exit(0)
}).catch(error=>{console.error(error);app.exit(1)})
