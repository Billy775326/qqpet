const { resizeViewport } = require('./viewport.cjs')
const { app, BrowserWindow, ipcMain } = require('electron')
const { readFileSync, writeFileSync, mkdtempSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { pathToFileURL } = require('node:url')
const assert = require('node:assert/strict')

const profile = mkdtempSync(resolve('dist/quantity-profile-'))
app.setPath('userData', profile)
app.setPath('sessionData', profile)
app.setAppLogsPath(join(profile, 'logs'))
ipcMain.handle('fixture:load', () => ({ settings: { hd: false }, petInfo: { growth: 0 }, petComputedlInfo: { level: 1 }, selfGoodUseOption: {} }))
ipcMain.on('fixture:save', event => { event.returnValue = null })

app.whenReady().then(async () => {
  const prepared = JSON.parse(readFileSync('dist/ui-shop-prepared.json', 'utf8'))
  const assetRoot = pathToFileURL(resolve(process.env.QQPET_TEST_RESOURCES || 'resources') + '/').href
  const html = resolve('dist/quantity-test.html')
  writeFileSync(html, '<!doctype html><html><head><meta charset="UTF-8"><base href="' + assetRoot + '"><style>' + prepared.css.replaceAll('url(/pet/', 'url(' + assetRoot + 'pet/') + '</style></head><body></body></html>')
  const win = new BrowserWindow({ width: 800, height: 600, useContentSize: true, show: false, webPreferences: {
    preload: join(__dirname, 'shop-preload.cjs'), sandbox: true, contextIsolation: true, offscreen: true, backgroundThrottling: false,
  } })
  const evaluate = expression => win.webContents.executeJavaScript(expression)
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
  await win.loadFile(html)
  await resizeViewport(win, 800, 600)
  await evaluate('(async()=>{' + prepared.code + ';return true})()')
  if (!win.webContents.debugger.isAttached()) win.webContents.debugger.attach('1.3')
  const cdp = (method, params) => win.webContents.debugger.sendCommand(method, params)
  await cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
  const move = async selector => {
    const point = await evaluate('(()=>{const r=document.querySelector(' + JSON.stringify(selector) + ').getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()')
    await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', ...point })
    return point
  }
  const click = async selector => {
    const point = await move(selector)
    for (const type of ['mousePressed', 'mouseReleased'])
      await cdp('Input.dispatchMouseEvent', { type, ...point, button: 'left', clickCount: 1 })
  }
  const value = () => evaluate('Number(document.querySelector(".chooseNum .content").textContent)')
  const state = () => evaluate('[...document.querySelectorAll(".quantityButton")].map(e=>e.disabled)')
  const open = async (max, sweet) => {
    await evaluate('fixture.openQuantity(' + max + ',' + sweet + ')')
    await pause(80)
  }
  const results = []
  for (const sweet of [true, false]) {
    await open(30, sweet)
    assert.equal(await value(), 30)
    assert.deepEqual(await state(), [false, false, false, true, true, true])
    for (const cls of ['add', 'addUp', 'addUpOver']) {
      await click('.' + cls)
      await evaluate('document.querySelector(".' + cls + '").click();true')
      assert.equal(await value(), 30, 'disabled increment must not change the quantity')
    }
    await move('.cutUpOver')
    await pause(150)
    assert.notEqual(await evaluate('getComputedStyle(document.querySelector(".cutUpOver")).transform'), 'none', 'enabled double arrow responds to hover')
    const frameBefore = await evaluate('document.querySelector(".boxFrame").getBoundingClientRect().x')
    await click('.cutUpOver')
    assert.equal(await value(), 1)
    assert.deepEqual(await state(), [true, true, true, false, false, false])
    assert.equal(await evaluate('document.querySelector(".boxFrame").getBoundingClientRect().x'), frameBefore, 'quantity controls do not move the dialog')
    assert.ok(await evaluate('document.querySelector(".cutUpOver").getAnimations().some(a=>a.effect.getKeyframes().length===3)'), 'jump to minimum plays click feedback even as it becomes disabled')
    await pause(230)
    assert.equal(await evaluate('getComputedStyle(document.querySelector(".cutUpOver")).transform'), 'none', 'disabled arrow no longer responds to hover')
    assert.equal(await evaluate('getComputedStyle(document.querySelector(".cutUpOver")).opacity'), '0.35')
    for (const cls of ['cutUpOver', 'cutUp', 'cut']) {
      await click('.' + cls)
      await evaluate('document.querySelector(".' + cls + '").click();true')
      assert.equal(await value(), 1, 'disabled decrement must not change the quantity')
    }
    await click('.addUp')
    assert.equal(await value(), 11)
    assert.deepEqual(await state(), [false, false, false, false, false, false])
    await click('.cut')
    assert.equal(await value(), 10)
    await click('.cutUp')
    assert.equal(await value(), 1, 'minus ten clamps to minimum')
    await click('.addUpOver')
    assert.equal(await value(), 30)
    assert.ok(await evaluate('document.querySelector(".addUpOver").getAnimations().some(a=>a.effect.getKeyframes().length===3)'), 'jump to maximum plays click feedback')
    await click('.cut')
    assert.equal(await value(), 29)
    await click('.addUp')
    assert.equal(await value(), 30, 'plus ten clamps to maximum')
    await click('.cutUpOver')
    await click('.add')
    assert.equal(await value(), 2)
    await click('.windowViewButSubmit')
    assert.equal(await evaluate('window.quantitySubmitted'), 2, 'confirmation receives selected quantity')
    assert.equal(await evaluate('!!document.querySelector(".ui-window")'), false)
    await open(1, sweet)
    assert.deepEqual(await state(), [true, true, true, true, true, true], 'single available quantity disables all controls')
    await click('.windowViewBut')
    results.push({ sweet, bounds: true, animation: true, submit: true, singleQuantity: true })
  }

  // Exercise the complete pointer sequence, including release outside the button.
  const expected = { cutUpOver: 1, cutUp: 10, cut: 19, add: 21, addUp: 30, addUpOver: 30 }
  for (const [cls, after] of Object.entries(expected)) {
    await open(30, true)
    await click('.cutUp')
    await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 0, y: 0 })
    await pause(230)
    const baseColors = await evaluate('[...document.querySelectorAll(".quantityButton")].map(e=>getComputedStyle(e).color)')
    assert.equal(new Set(baseColors).size, 1, 'all enabled quantity buttons share one base color')
    assert.equal(await value(), 20)
    const point = await move('.' + cls)
    await pause(150)
    const hoverColor = await evaluate('getComputedStyle(document.querySelector(".' + cls + '")).color')
    assert.notEqual(hoverColor, baseColors[0], 'hover uses the second color on ' + cls)
    assert.equal(await value(), 20, 'hover alone does not change the quantity')
    if (cls === 'add') writeFileSync('dist/quantity-hover.png', (await win.webContents.capturePage()).toPNG())
    await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', ...point, button: 'left', clickCount: 1 })
    await pause(150)
    assert.equal(await value(), 20, 'press waits for release before committing the quantity')
    const pressed = await evaluate('(()=>{const s=getComputedStyle(document.querySelector(".' + cls + '"));return{background:s.backgroundColor,transform:s.transform}})()')
    assert.equal(pressed.background, hoverColor, 'press fills the button with the highlight color')
    assert.notEqual(pressed.transform, 'none', 'press has visible motion feedback')
    if (cls === 'add') writeFileSync('dist/quantity-pressed.png', (await win.webContents.capturePage()).toPNG())
    await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', ...point, button: 'left', clickCount: 1 })
    assert.equal(await value(), after, 'release commits exactly one quantity change')
    assert.ok(await evaluate('document.querySelector(".' + cls + '").getAnimations().some(a=>a.effect.getKeyframes().length===3)'), 'every button plays release feedback')
    assert.ok(await evaluate('document.querySelector(".chooseNum .content").getAnimations().length>0'), 'the updated quantity receives matching feedback')
    if (cls === 'add') {
      await pause(80)
      writeFileSync('dist/quantity-updated.png', (await win.webContents.capturePage()).toPNG())
    }
  }
  await open(30, true)
  await click('.cutUp')
  const cancelPoint = await move('.add')
  await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', ...cancelPoint, button: 'left', clickCount: 1 })
  await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 0, y: 0 })
  await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', x: 0, y: 0, button: 'left', clickCount: 1 })
  assert.equal(await value(), 20, 'releasing outside cancels the pending change')

  await cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await open(30, true)
  await click('.cutUpOver')
  assert.equal(await value(), 1)
  assert.equal(await evaluate('document.querySelector(".cutUpOver").getAnimations().length'), 0, 'reduced motion suppresses click animation')
  await move('.addUpOver')
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".addUpOver")).transform'), 'none', 'reduced motion suppresses hover movement')
  await cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
  const layouts = []
  for (const [width, height, scale] of [[800, 600, 1], [320, 240, 1.25], [426, 234, 3]]) {
    await resizeViewport(win, width, height, scale)
    await open(30, true)
    const bounds = await evaluate('[...document.querySelectorAll(".quantityButton")].map(e=>{const r=e.getBoundingClientRect();return{x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:r.width,height:r.height}})')
    for (const b of bounds) assert.ok(b.width > 0 && b.height > 0 && b.x >= 0 && b.y >= 0 && b.right <= width && b.bottom <= height, 'all quantity buttons fit in the viewport')
    await click('.cutUpOver')
    assert.equal(await value(), 1)
    await pause(230)
    layouts.push({ width, height, scale })
  }
  await resizeViewport(win, 800, 600)
  await open(30, true)
  await click('.cutUpOver')
  await pause(230)
  writeFileSync('dist/quantity-minimum.png', (await win.webContents.capturePage()).toPNG())
  await click('.addUpOver')
  await pause(230)
  writeFileSync('dist/quantity-maximum.png', (await win.webContents.capturePage()).toPNG())
  writeFileSync('dist/quantity-results.json', JSON.stringify({ results, layouts, reducedMotion: true, colorStates: true, pointerSequence: true, cancelledPress: true }, null, 2))
  console.log('Quantity picker passed:', JSON.stringify({ results, layouts, reducedMotion: true, colorStates: true, pointerSequence: true, cancelledPress: true }))
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
