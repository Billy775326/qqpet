const { resizeViewport } = require('./viewport.cjs')
const { app, BrowserWindow, ipcMain } = require('electron')
const { readFileSync, writeFileSync, mkdtempSync } = require('node:fs')
const { resolve, join } = require('node:path')
const { pathToFileURL } = require('node:url')
const assert = require('node:assert/strict')

const profile = mkdtempSync(resolve('dist/quantity-profile-'))
app.setPath('userData', profile)
app.setPath('sessionData', profile)
app.setAppLogsPath(join(profile, 'logs'))
ipcMain.handle('fixture:load', () => ({ settings: { hd: false }, petInfo: { growth: 0 }, petComputedlInfo: { level: 1 }, selfGoodUseOption: {} }))
ipcMain.on('fixture:save', event => { event.returnValue = null })

app.whenReady().then(async () => {
  const prepared = JSON.parse(readFileSync('dist/ui-shop-prepared.json', 'utf8'))
  const assetRoot = pathToFileURL(resolve(process.env.QQPET_TEST_RESOURCES || 'resources') + '/').href
  const html = resolve('dist/quantity-test.html')
  writeFileSync(html, '<!doctype html><html><head><meta charset="UTF-8"><base href="' + assetRoot + '"><style>' + prepared.css.replaceAll('url(/pet/', 'url(' + assetRoot + 'pet/') + '</style></head><body></body></html>')
  const win = new BrowserWindow({ width: 800, height: 600, useContentSize: true, show: false, webPreferences: {
    preload: join(__dirname, 'shop-preload.cjs'), sandbox: true, contextIsolation: true, offscreen: true, backgroundThrottling: false,
  } })
  const evaluate = expression => win.webContents.executeJavaScript(expression)
  const pause = ms => new Promise(resolve => setTimeout(resolve, ms))
  await win.loadFile(html)
  await resizeViewport(win, 800, 600)
  await evaluate('(async()=>{' + prepared.code + ';return true})()')
  if (!win.webContents.debugger.isAttached()) win.webContents.debugger.attach('1.3')
  const cdp = (method, params) => win.webContents.debugger.sendCommand(method, params)
  await cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
  const move = async selector => {
    const point = await evaluate('(()=>{const r=document.querySelector(' + JSON.stringify(selector) + ').getBoundingClientRect();return{x:r.x+r.width/2,y:r.y+r.height/2}})()')
    await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', ...point })
    return point
  }
  const click = async selector => {
    const point = await move(selector)
    for (const type of ['mousePressed', 'mouseReleased'])
      await cdp('Input.dispatchMouseEvent', { type, ...point, button: 'left', clickCount: 1 })
  }
  const value = () => evaluate('Number(document.querySelector(".chooseNum .content").textContent)')
  const state = () => evaluate('[...document.querySelectorAll(".quantityButton")].map(e=>e.disabled)')
  const open = async (max, sweet) => {
    await evaluate('fixture.openQuantity(' + max + ',' + sweet + ')')
    await pause(80)
  }
  const selectors = ['cutUpOver', 'cut', 'add', 'addUpOver']
  const results = []
  const hintState = cls => evaluate('(()=>{const e=document.querySelector(".' + cls + '"),h=e.querySelector(".quantityStepHint");return h?{visible:getComputedStyle(h).visibility,opacity:getComputedStyle(h).opacity,src:h.src,loaded:h.complete&&h.naturalWidth>0,label:e.getAttribute("aria-label")}:null})()')
  for (const sweet of [true, false]) {
    await open(30, sweet)
    await evaluate('Promise.all([...document.querySelectorAll(".quantityStepHint")].map(i=>i.decode()))')
    assert.equal(await value(), 30)
    const artwork = await evaluate('[...document.querySelectorAll(".quantityButton")].map(e=>{const s=getComputedStyle(e);return{image:s.backgroundImage,width:s.width,height:s.height,border:s.borderWidth,text:e.textContent}})')
    assert.equal(artwork.length, 4, 'ten-step controls are consolidated into the double arrows')
    const originalImages = ['left.svg', 'shoping_07.gif', 'shoping_09.gif', 'right.svg']
    artwork.forEach((button, index) => {
      assert.ok(button.image.includes(originalImages[index]), 'original image buttons remain')
      assert.equal(button.width, '18px')
      assert.equal(button.height, '18px')
      assert.equal(button.border, '0px')
      assert.equal(button.text, '')
    })
    assert.equal(await evaluate('document.querySelectorAll(".cutUp,.addUp").length'), 0, 'no duplicate ten-step buttons')
    for (const [cls, image, label] of [['cutUpOver', 'cut.svg', '−10'], ['addUpOver', 'add.svg', '+10']]) {
      const hint = await hintState(cls)
      assert.ok(hint.src.endsWith(image) && hint.loaded && hint.label.includes(label), 'arrow hint reuses the old ten-step artwork and accessible label')
      assert.equal(hint.visible, 'hidden')
    }
    assert.deepEqual(await state(), [false, false, true, true])
    for (const cls of ['add', 'addUpOver']) {
      await click('.' + cls)
      await evaluate('document.querySelector(".' + cls + '").click();true')
      assert.equal(await value(), 30, 'disabled increments have no effect')
    }
    const frameBefore = await evaluate('document.querySelector(".boxFrame").getBoundingClientRect().x')
    await click('.cutUpOver')
    assert.equal(await value(), 20, 'left double arrow subtracts ten rather than jumping to minimum')
    await click('.cutUpOver')
    assert.equal(await value(), 10)
    await click('.cutUpOver')
    assert.equal(await value(), 1, 'subtracting ten clamps to minimum')
    await pause(230)
    assert.deepEqual(await state(), [true, true, false, false])
    assert.equal((await hintState('cutUpOver')).visible, 'hidden', 'disabled arrows never show active hints')
    assert.equal(await evaluate('getComputedStyle(document.querySelector(".cutUpOver")).transform'), 'none')
    assert.equal(await evaluate('getComputedStyle(document.querySelector(".cutUpOver")).opacity'), '0.35')
    assert.equal(await evaluate('document.querySelector(".boxFrame").getBoundingClientRect().x'), frameBefore, 'quantity controls do not drag the dialog')
    for (const cls of ['cutUpOver', 'cut']) {
      await click('.' + cls)
      await evaluate('document.querySelector(".' + cls + '").click();true')
      assert.equal(await value(), 1)
    }
    await click('.addUpOver')
    assert.equal(await value(), 11, 'right double arrow adds ten rather than jumping to maximum')
    assert.deepEqual(await state(), [false, false, false, false])
    await click('.addUpOver')
    assert.equal(await value(), 21)
    await click('.addUpOver')
    assert.equal(await value(), 30, 'adding ten clamps to maximum')
    await click('.cut')
    assert.equal(await value(), 29)
    await click('.add')
    assert.equal(await value(), 30)
    for (let i = 0; i < 3; i++) await click('.cutUpOver')
    await click('.add')
    assert.equal(await value(), 2)
    await click('.windowViewButSubmit')
    assert.equal(await evaluate('window.quantitySubmitted'), 2)
    assert.equal(await evaluate('!!document.querySelector(".ui-window")'), false)
    await open(1, sweet)
    assert.deepEqual(await state(), [true, true, true, true], 'single available quantity disables all controls')
    await open(7, sweet)
    await click('.cutUpOver')
    assert.equal(await value(), 1, 'step larger than available range clamps safely')
    await click('.addUpOver')
    assert.equal(await value(), 7)
    await click('.windowViewBut')
    results.push({ sweet, tenStepArrows: true, singleSteps: true, bounds: true, submit: true, originalArtwork: true })
  }

  const expected = { cutUpOver: 10, cut: 19, add: 21, addUpOver: 30 }
  let yellowHover
  for (const [cls, after] of Object.entries(expected)) {
    await open(30, true)
    await click('.cutUpOver')
    await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 0, y: 0 })
    await pause(230)
    const baseTints = await evaluate('[...document.querySelectorAll(".quantityButton")].map(e=>getComputedStyle(e).filter)')
    assert.equal(new Set(baseTints).size, 1, 'enabled controls share the green base tint')
    assert.equal(await value(), 20)
    const point = await move('.' + cls)
    await pause(150)
    const hoverTint = await evaluate('getComputedStyle(document.querySelector(".' + cls + '")).filter')
    assert.notEqual(hoverTint, baseTints[0])
    yellowHover ??= hoverTint
    assert.equal(hoverTint, yellowHover, 'every button uses the same yellow hover state')
    assert.equal(await value(), 20, 'hover does not change quantity')
    const hint = await hintState(cls)
    if (hint) {
      assert.equal(hint.visible, 'visible')
      assert.equal(hint.opacity, '1')
      const hintBounds = await evaluate('(()=>{const r=document.querySelector(".' + cls + ' .quantityStepHint").getBoundingClientRect();return{x:r.x,y:r.y,right:r.right,bottom:r.bottom}})()')
      assert.ok(hintBounds.x >= 0 && hintBounds.y >= 0 && hintBounds.right <= 800 && hintBounds.bottom <= 600)
      writeFileSync('dist/quantity-' + cls + '-hover.png', (await win.webContents.capturePage()).toPNG())
    }
    await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', ...point, button: 'left', clickCount: 1 })
    await pause(150)
    assert.equal(await value(), 20, 'press commits only on release')
    const pressed = await evaluate('(()=>{const s=getComputedStyle(document.querySelector(".' + cls + '"));return{filter:s.filter,transform:s.transform}})()')
    assert.notEqual(pressed.filter, hoverTint)
    assert.notEqual(pressed.transform, 'none')
    await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', ...point, button: 'left', clickCount: 1 })
    assert.equal(await value(), after, 'release changes the quantity exactly once')
    assert.ok(await evaluate('document.querySelector(".' + cls + '").getAnimations().some(a=>a.effect.getKeyframes().length===3)'))
    assert.ok(await evaluate('document.querySelector(".chooseNum .content").getAnimations().length>0'))
    await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 0, y: 0 })
    if (hint) assert.equal((await hintState(cls)).visible, 'hidden', 'leaving an arrow dismisses its hint')
  }
  await open(30, true)
  await click('.cutUpOver')
  const cancelPoint = await move('.addUpOver')
  await cdp('Input.dispatchMouseEvent', { type: 'mousePressed', ...cancelPoint, button: 'left', clickCount: 1 })
  await cdp('Input.dispatchMouseEvent', { type: 'mouseMoved', x: 0, y: 0 })
  await cdp('Input.dispatchMouseEvent', { type: 'mouseReleased', x: 0, y: 0, button: 'left', clickCount: 1 })
  assert.equal(await value(), 20, 'releasing outside cancels the pending change')

  await cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'reduce' }] })
  await open(30, true)
  await click('.cutUpOver')
  assert.equal(await value(), 20)
  assert.equal(await evaluate('document.querySelector(".cutUpOver").getAnimations().length'), 0)
  assert.equal(await evaluate('document.querySelector(".chooseNum .content").getAnimations().length'), 0)
  await move('.addUpOver')
  assert.equal(await evaluate('getComputedStyle(document.querySelector(".addUpOver")).transform'), 'none')
  assert.equal((await hintState('addUpOver')).visible, 'visible', 'reduced motion retains the step hint')
  await cdp('Emulation.setEmulatedMedia', { features: [{ name: 'prefers-reduced-motion', value: 'no-preference' }] })
  const layouts = []
  for (const [width, height, scale] of [[800, 600, 1], [320, 240, 1.25], [426, 234, 3]]) {
    await resizeViewport(win, width, height, scale)
    await open(30, true)
    await click('.cutUpOver')
    assert.equal(await value(), 20)
    await pause(230)
    for (const cls of ['cutUpOver', 'addUpOver']) {
      await move('.' + cls)
      await pause(150)
      const bounds = await evaluate('[...document.querySelectorAll(".quantityButton"),document.querySelector(".' + cls + ' .quantityStepHint")].map(e=>{const r=e.getBoundingClientRect();return{x:r.x,y:r.y,right:r.right,bottom:r.bottom,width:r.width,height:r.height}})')
      for (const b of bounds) assert.ok(b.width > 0 && b.height > 0 && b.x >= 0 && b.y >= 0 && b.right <= width && b.bottom <= height, 'buttons and image hints fit in the viewport')
    }
    layouts.push({ width, height, scale })
  }
  await resizeViewport(win, 800, 600)
  await open(30, true)
  for (let i = 0; i < 3; i++) await click('.cutUpOver')
  await pause(230)
  writeFileSync('dist/quantity-minimum.png', (await win.webContents.capturePage()).toPNG())
  for (let i = 0; i < 3; i++) await click('.addUpOver')
  await pause(230)
  writeFileSync('dist/quantity-maximum.png', (await win.webContents.capturePage()).toPNG())
  const report = { results, layouts, reducedMotion: true, yellowHover: true, imageHints: true, pointerSequence: true, cancelledPress: true }
  writeFileSync('dist/quantity-results.json', JSON.stringify(report, null, 2))
  console.log('Quantity picker passed:', JSON.stringify(report))
  app.exit(0)
}).catch(error => { console.error(error); app.exit(1) })
